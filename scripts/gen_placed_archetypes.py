#!/usr/bin/env python3
"""Generate substrate/PLACED_ARCHETYPES.md — one readable master view of every placed archetype
(kati 2026-10-16: "where are we saving arcs? can we make a master file for placed archetypes in enki?").

GENERATED VIEW, NOT A SOURCE. The authority is substrate/placement_registry.json (Tier-A); the arc
math is Nammu engines/archetype_events.py; the evidence is the cards. This file only renders the
registry so it cannot drift (the boot-frame lesson, memory project_corpus_slip_pump): edit the
registry, then rerun. tests/test_placed_archetypes_current.py fails if the file is stale.

    python3 scripts/gen_placed_archetypes.py          # rewrite the file
    python3 scripts/gen_placed_archetypes.py --check  # exit 1 if stale
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REGISTRY = ROOT / 'substrate' / 'placement_registry.json'
OUT = ROOT / 'substrate' / 'PLACED_ARCHETYPES.md'


def _cell(x) -> str:
    if x is None:
        return '—'
    if isinstance(x, (list, tuple)):
        return ' → '.join(str(v) for v in x)
    return str(x).replace('|', '/').replace('\n', ' ')


def render(reg: dict) -> str:
    entries = {k: v for k, v in reg.items() if not k.startswith('_') and isinstance(v, dict)}
    arcs = {k: v for k, v in entries.items() if v.get('placement_class') == 'EVENT_ARC'}
    others = {k: v for k, v in entries.items() if k not in arcs}
    lines = [
        '# Placed archetypes — master view',
        '',
        '> GENERATED by `scripts/gen_placed_archetypes.py` from `substrate/placement_registry.json`. Do not edit',
        '> by hand — edit the registry and rerun. Arc math: Nammu `engines/archetype_events.py`; evidence: the cards.',
        f"> Registry schema {reg.get('_meta', {}).get('schema_version', '?')}. {len(arcs)} event-arcs, "
        f"{len(others)} other placements.",
        '',
        '## Event-arcs (archetype = a sky event: actor × place × phase; the arc is its extent)',
        '',
        '| archetype | stratum | actor | boundaries | source sky / recurrence | engine | status | source |',
        '|---|---|---|---|---|---|---|---|',
    ]
    for name in sorted(arcs, key=lambda n: (arcs[n].get('event_arc', {}).get('actor', ''), n)):
        v = arcs[name]
        ea = v.get('event_arc', {})
        sp = v.get('substrate_position', {})
        sky = '; '.join(x for x in (sp.get('source_sky'), sp.get('recurrence')) if x) or '—'
        lines.append(f"| **{name}** | {_cell(v.get('stratum'))} | {_cell(ea.get('actor') or sp.get('actor_planet'))} "
                     f"| {_cell(ea.get('boundaries'))} | {_cell(sky)} | `{_cell(ea.get('engine'))}` "
                     f"| {_cell(v.get('placement_status'))} | {_cell(v.get('placement_source'))} |")
    lines += ['', '## Other placements (not event-arcs)', '',
              '| archetype | stratum | class | status | activation (live) | source |', '|---|---|---|---|---|---|']
    for name in sorted(others):
        v = others[name]
        ca = v.get('cyclic_activation')
        act = (f"{ca.get('transit_planet')} × Venus conjunction (`{ca.get('engine')}`)" if ca
               else v.get('activation_cycle') or v.get('activation'))   # superseded_activation never shown
        lines.append(f"| **{name}** | {_cell(v.get('stratum'))} | {_cell(v.get('placement_class'))} "
                     f"| {_cell(v.get('placement_status'))} | {_cell(act)} | {_cell(v.get('placement_source'))} |")
    blocked = reg.get('_blocked_pending_placement', {})
    names = [k for k in blocked if not k.startswith('_')]
    if names:
        lines += ['', '## Blocked — pending placement', '', ', '.join(sorted(names))]
    return '\n'.join(lines) + '\n'


def main() -> int:
    text = render(json.loads(REGISTRY.read_text()))
    if '--check' in sys.argv:
        current = OUT.read_text() if OUT.exists() else ''
        if current != text:
            print('PLACED_ARCHETYPES.md is stale — run scripts/gen_placed_archetypes.py')
            return 1
        return 0
    OUT.write_text(text)
    print(f'wrote {OUT}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
